namespace
{
    namespace abi = wio::wir_backend::abi;
    namespace bridge = wio::vm::detail;
    constexpr std::uint64_t PodId = 810;
    constexpr std::uint64_t FieldId = 811;

    struct Pod
    {
        double padding = 2.5;
        std::int32_t value = 7;
        std::int32_t hidden = 99;
    };
} // namespace

namespace wio::wir_backend::abi
{
    template <> struct NativePodProjectionAccess<Pod>
    {
        static void* resolve(void* storage, std::uint64_t rootId, std::uint64_t targetId, std::uint64_t offset,
                             std::uint64_t size, const std::type_info& requested) noexcept
        {
            return storage && rootId == PodId && targetId == FieldId && offset == offsetof(Pod, value) &&
                           size == sizeof(std::int32_t) && requested == typeid(std::int32_t)
                       ? &static_cast<Pod*>(storage)->value
                       : nullptr;
        }
    };
} // namespace wio::wir_backend::abi

namespace
{

    struct WireGuard
    {
        WioNativeAbiValue value;
        ~WireGuard()
        {
            WioNativeAbiReleaseValue(&value);
        }
    };

    bool expect(bool condition, const char* message)
    {
        if (!condition)
            std::cerr << message << '\n';
        return condition;
    }

    WioNativeAbiValue reference(void* token, std::uint64_t size, bool mutableAccess, bool projected = false)
    {
        WioNativeAbiValue wire;
        wire.kind = WIO_NATIVE_ABI_REFERENCE;
        wire.flags = WIO_NATIVE_ABI_VALUE_BORROWED | (mutableAccess ? WIO_NATIVE_ABI_VALUE_MUTABLE : 0u) |
                     (projected ? WIO_NATIVE_ABI_VALUE_PROJECTED : 0u);
        wire.payload.mutableSlice = {token, size};
        return wire;
    }

    // Use real generated bytecode/adapters but remove the additive capability
    // bit, simulating a layout-v1 producer compiled before projections existed.
    bool qualifyLegacyProducer(const char* bytecodePath, const char* libraryPath)
    {
        struct Library
        {
#if defined(_WIN32)
            HMODULE handle;
            explicit Library(const char* path)
                : handle(LoadLibraryExW(std::filesystem::u8path(path).c_str(), nullptr, LOAD_WITH_ALTERED_SEARCH_PATH))
            {
            }
            ~Library()
            {
                if (handle)
                    FreeLibrary(handle);
            }
            void* symbol(const char* name) const
            {
                return reinterpret_cast<void*>(GetProcAddress(handle, name));
            }
#else
            void* handle;
            explicit Library(const char* path) : handle(dlopen(path, RTLD_NOW | RTLD_LOCAL))
            {
            }
            ~Library()
            {
                if (handle)
                    dlclose(handle);
            }
            void* symbol(const char* name) const
            {
                return dlsym(handle, name);
            }
#endif
        } library{libraryPath};
        if (!expect(library.handle != nullptr, "legacy qualification could not open producer"))
            return false;
        const auto registry = reinterpret_cast<WioGetNativeAbiRegistryFn>(library.symbol("WioGetNativeAbiRegistry"));
        const auto layouts = reinterpret_cast<WioGetNativePodLayoutApiFn>(library.symbol("WioGetNativePodLayoutApi"));
        const auto defaults =
            reinterpret_cast<WioGetNativePodDefaultApiFn>(library.symbol("WioGetNativePodDefaultApi"));
        if (!expect(registry && layouts && defaults, "producer qualification sidecars missing"))
            return false;
        std::ifstream input(std::filesystem::u8path(bytecodePath), std::ios::binary);
        const std::vector<char> bytes{std::istreambuf_iterator<char>{input}, std::istreambuf_iterator<char>{}};
        auto decoded = wio::bytecode::decode({reinterpret_cast<const std::byte*>(bytes.data()), bytes.size()});
        if (!expect(decoded.succeeded(), "legacy qualification bytecode decode failed"))
            return false;
        std::uint32_t entry = wio::bytecode::InvalidIndex;
        for (const auto& function : decoded.module.functions)
            if (decoded.module.string(function.name) == "Entry")
                entry = function.id;
        const auto* original = registry();
        const auto* layoutApi = layouts();
        const auto* defaultApi = defaults();
        if (!expect(original && layoutApi && defaultApi && entry != wio::bytecode::InvalidIndex,
                    "legacy qualification metadata incomplete"))
            return false;
        std::vector<WioNativeAbiFunctionDescriptor> descriptors{original->functions,
                                                                original->functions + original->functionCount};
        for (auto& descriptor : descriptors)
            descriptor.flags &= ~WIO_NATIVE_ABI_FUNCTION_PROJECTED_REFERENCES;
        const WioNativeAbiRegistry legacyRegistry{original->abiVersion, original->functionCount, descriptors.data()};
        wio::vm::Machine machine{decoded.module};
        std::string error;
        if (!expect(machine.registerNativeRegistry(legacyRegistry, *layoutApi, nullptr, nullptr, &error, defaultApi),
                    "legacy qualification registration failed"))
            return false;
        const auto result = machine.invoke(entry);
        return expect(!result.succeeded() && result.error().code == "WVM1225" &&
                          result.error().message.find("projections") != std::string::npos,
                      "legacy producer silently accepted overlapping POD references");
    }
} // namespace

int main(int argc, char** argv)
{
    if (argc == 3)
        return qualifyLegacyProducer(argv[1], argv[2]) ? 0 : 1;
    WireGuard root{abi::Codec<Pod, PodId>::write(Pod{})};
    auto rootReference = reference(&root.value, sizeof(WioNativeAbiValue), false);
    WioNativeAbiProjection projection{&root.value, PodId, FieldId, offsetof(Pod, value), sizeof(std::int32_t)};
    auto fieldReference = reference(&projection, sizeof(projection), true, true);
    abi::Frame frame;
    auto& packet = frame.borrow<Pod, PodId>(rootReference, false);
    auto& value = frame.borrow<std::int32_t, FieldId>(fieldReference, true);
    auto& repeated = frame.borrow<std::int32_t, FieldId>(fieldReference, true);
    bool passed = expect(&value == &packet.value && &value == &repeated, "projection created independent storage");
    value = 31;
    ++packet.hidden;
    frame.commit();
    const auto committedOwner = root.value.owner.state;
    frame.commit();
    const auto committed = abi::Codec<Pod, PodId>::read(root.value);
    passed &= expect(committed.value == 31 && committed.hidden == 100 && root.value.owner.state == committedOwner,
                     "mutable field under view root did not commit the entire producer POD");

    // A caught native failure commits the shared slot just like normal return.
    try
    {
        frame.borrow<std::int32_t, FieldId>(fieldReference, true) = 42;
        throw std::runtime_error("native fixture failure");
    }
    catch (const std::exception&)
    {
        frame.commit();
    }
    passed &= expect(abi::Codec<Pod, PodId>::read(root.value).value == 42, "exception copy-back lost field edits");

    const auto rejected = [&](const WioNativeAbiValue& wire, bool mutableAccess = false)
    {
        try
        {
            (void)frame.borrow<std::int32_t, FieldId>(wire, mutableAccess);
            return false;
        }
        catch (const abi::Error&)
        {
            return true;
        }
    };
    const auto original = projection;
    WioNativeAbiValue unknown;
    projection.root = &unknown;
    passed &= expect(rejected(fieldReference), "unbound projection root accepted");
    projection = original;
    ++projection.rootTypeId;
    passed &= expect(rejected(fieldReference), "wrong root identity accepted");
    projection = original;
    ++projection.typeId;
    passed &= expect(rejected(fieldReference), "wrong field identity accepted");
    projection = original;
    projection.offset = (std::numeric_limits<std::uint64_t>::max)();
    passed &= expect(rejected(fieldReference), "overflowing projection offset accepted");
    projection = original;
    projection.offset = sizeof(Pod) - 1;
    passed &= expect(rejected(fieldReference), "out-of-bounds field accepted");
    projection = original;
    ++projection.offset;
    passed &= expect(rejected(fieldReference), "misaligned projection accepted");
    projection = original;
    ++projection.size;
    passed &= expect(rejected(fieldReference), "wrong field extent accepted");
    projection = original;
    auto malformed = fieldReference;
    --malformed.payload.mutableSlice.size;
    passed &= expect(rejected(malformed), "truncated projection descriptor accepted");
    malformed = fieldReference;
    malformed.payload.mutableSlice.data = nullptr;
    passed &= expect(rejected(malformed), "null descriptor accepted");
    malformed = fieldReference;
    malformed.flags &= ~WIO_NATIVE_ABI_VALUE_MUTABLE;
    passed &= expect(rejected(malformed, true), "view field upgraded to a mutable reference");
    malformed = fieldReference;
    malformed.flags &= ~WIO_NATIVE_ABI_VALUE_BORROWED;
    passed &= expect(rejected(malformed), "unborrowed projection accepted");

    WireGuard scalar{abi::Codec<std::int32_t, FieldId>::write(3)};
    auto scalarReference = reference(&scalar.value, sizeof(WioNativeAbiValue), true);
    (void)frame.borrow<std::int32_t, FieldId>(scalarReference, true);
    projection = {&scalar.value, FieldId, FieldId, 0, sizeof(std::int32_t)};
    passed &= expect(rejected(fieldReference), "scalar token accepted as a POD projection root");

    // Layout lookup uses storage identity, not equivalent component values.
    wio::bytecode::Module module;
    module.types = {
        wio::bytecode::Type{.kind = 5},
        wio::bytecode::Type{.kind = 28, .nominalKind = 1, .nominalRepresentation = 1, .fields = {{.type = 0}}}};
    bridge::NativePodLayouts layouts;
    layouts.types[1] = {PodId,   sizeof(Pod), alignof(Pod),
                        nullptr, nullptr,     {{FieldId, offsetof(Pod, value), sizeof(std::int32_t), 5}}};
    auto aggregate = wio::vm::Value::component(1, {wio::vm::Value::signedInteger(7)});
    auto independent = wio::vm::Value::component(1, {wio::vm::Value::signedInteger(7)});
    bridge::NativePodProjection located;
    passed &= expect(bridge::findNativePodProjection(module, aggregate, 1, *aggregate.field(0), layouts, located) &&
                         located.offset == offsetof(Pod, value) && located.typeId == FieldId,
                     "projection lookup ignored producer field offset");
    passed &= expect(!bridge::findNativePodProjection(module, aggregate, 1, *independent.field(0), layouts, located),
                     "independent equal-valued component was incorrectly aliased");
    passed &= expect(!bridge::findNativePodProjection(module, aggregate, 1, *aggregate.field(0), layouts, located, 129),
                     "projection traversal ignored its recursion budget");
    return passed ? 0 : 1;
}
